// Converts the large source PNGs in public/images/graphic-design/ into
// web-sized WebP files and writes a manifest (size + placeholder colour)
// that the gallery reads. Re-run after adding or replacing artwork:
//   npm run optimize:images
import sharp from 'sharp'
import { readdir, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'

const SRC = 'public/images/graphic-design'
const OUT = path.join(SRC, 'optimized')
const MANIFEST = 'src/data/designImages.generated.ts'
const WIDTHS = [640, 1200, 1800]

await mkdir(OUT, { recursive: true })
const files = (await readdir(SRC)).filter((f) => /\.(png|jpe?g)$/i.test(f)).sort()

const manifest = {}
for (const file of files) {
  const name = file.replace(/\.[^.]+$/, '')
  const input = sharp(path.join(SRC, file))
  const { width, height } = await input.metadata()
  const { dominant } = await input.stats()
  const hex = '#' + [dominant.r, dominant.g, dominant.b].map((v) => v.toString(16).padStart(2, '0')).join('')

  for (const w of WIDTHS) {
    await sharp(path.join(SRC, file))
      .resize({ width: Math.min(w, width), withoutEnlargement: true })
      .webp({ quality: 80 })
      .toFile(path.join(OUT, `${name}-${w}.webp`))
  }

  manifest[`/images/graphic-design/${file}`] = { name, width, height, color: hex }
  console.log(`${file} → ${WIDTHS.map((w) => `${name}-${w}.webp`).join(', ')}`)
}

const body = `// Generated by scripts/optimize-images.mjs — do not edit by hand.
export interface DesignImageMeta {
  name: string
  width: number
  height: number
  /** Dominant colour, shown while the image loads */
  color: string
}

export const designImages: Record<string, DesignImageMeta> = ${JSON.stringify(manifest, null, 2)}

export const OPTIMIZED_BASE = '/images/graphic-design/optimized'
export const OPTIMIZED_WIDTHS = ${JSON.stringify(WIDTHS)} as const
`
await writeFile(MANIFEST, body)
console.log(`Wrote ${MANIFEST}`)
